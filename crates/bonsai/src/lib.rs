use gpui_kit::{
    AppContext as _, Bounds, TitlebarOptions, WindowBounds, WindowOptions, point, px, size,
};
use ui::{app::AppConfig, app_theme};

/// Opens Bonsai's window and runs until the app quits.
pub fn run() {
    askpass::enable();
    let application = gpui_kit::platform::application().with_assets(gpui_icons::LucideAssetSource);
    application.run(|cx| {
        let options = AppConfig::new("Bonsai")
            .themes(app_theme::light(), app_theme::dark())
            .appearance(app_theme::APPEARANCE)
            .window_options(WindowOptions {
                // Bonsai draws its own title bar (workspace/title_bar.rs), with
                // the traffic lights centered in it.
                titlebar: Some(TitlebarOptions {
                    title: None,
                    appears_transparent: true,
                    traffic_light_position: Some(point(px(16.), px(15.))),
                }),
                app_owns_titlebar_drag: true,
                ..WindowOptions::default()
            })
            .install(cx);
        commands::install(cx);
        let data_dir = session::data_dir();
        let settings_path = settings::settings_path(&data_dir);
        settings::install(
            settings::Settings::load(&settings_path),
            Some(settings_path),
            cx,
        );
        cx.on_action(|_: &commands::Quit, cx| cx.quit());
        cx.on_window_closed(|cx, _| {
            if cx.windows().is_empty() {
                cx.quit();
            }
        })
        .detach();

        let session_path = session::data_dir().join("session.json");
        let session = session::Session::load(&session_path);
        let bounds = Bounds::centered(None, size(px(1280.), px(820.)), cx);
        cx.open_window(
            WindowOptions {
                window_bounds: Some(WindowBounds::Windowed(bounds)),
                window_min_size: Some(size(px(900.), px(560.))),
                ..options
            },
            |window, cx| {
                ui::theme::follow_system(window, cx).detach();
                cx.new(|cx| {
                    workspace::Workspace::new(session, Some(session_path), true, window, cx)
                })
            },
        )
        .expect("open the Bonsai window");
        cx.activate(true);
    });
}
